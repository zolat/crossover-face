"""Export each lattice's dots as JSON, for the web configurator's preview.

The web preview colours dots; it does not decide where they are. Every position, ring
and cross orientation comes from here, computed the way ``DotGrid`` computes them — the
*integer* ring thickness ``ringBounds()`` uses, and ``orientationFor()``'s tangent
thresholds — rather than ``mockup.py``'s float ``ring_map``, which puts a few dots in a
different ring from the watch (4 at 390, 16 at 454).

The lattice constants are read from ``mockup.LATTICES``, which ``MatrixTest`` already
pins to ``source-lattice/*/Lattice.mc``. Per-ring dot counts are pinned again, from the
watch's side: ``GeometryTest.mc`` carries them in a generated block and asserts them
against the ``DotGrid`` the build actually made.

Usage::

    python3 tools/geometry_export.py            # write web/configurator/public/geometry/
    python3 tools/geometry_export.py --check    # fail if anything written is stale
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mockup  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "web" / "configurator" / "public" / "geometry"
MONKEYC_TEST = REPO / "source" / "tests" / "GeometryTest.mc"
BLOCK_START = "    // --- generated by tools/geometry_export.py: do not edit ---"
BLOCK_END = "    // --- end of generated counts ---"

RINGS = 4
PITCH, DOT = mockup.PITCH, mockup.DOT
# DotGrid's orientation thresholds, verbatim.
TAN_11_25, TAN_33_75, TAN_56_25, TAN_78_75 = 0.198912, 0.668179, 1.496606, 5.027339
ARMS = [(2, 0, 0, 2), (2, 1, -1, 2), (2, 2, -2, 2), (1, 2, -2, 1)]
ORIENTATIONS = 4

# The display's diameter as Garmin publishes it, for the preview's real-size view.
# Nominal figures, rounded to a tenth of an inch, but they agree with the ~325ppi every
# one of these panels has: 390/1.2 = 325, 416/1.3 = 320, 454/1.4 = 324.
DISPLAY_INCHES = {
    "instinctcrossoveramoled": 1.2,
    "epix2pro42mm": 1.2,
    "epix2": 1.3,
    "epix2pro47mm": 1.3,
    "epix2pro51mm": 1.4,
}


def orientation_for(dx: int, dy: int) -> int:
    """DotGrid.orientationFor, as an ARMS row rather than a flat offset."""
    ax, ay = abs(dx), abs(dy)
    if ax == 0:
        step = 0
    else:
        ratio = ay / ax
        if ratio < TAN_11_25:
            step = 0
        elif ratio < TAN_33_75:
            step = 1
        elif ratio < TAN_56_25:
            step = 2
        elif ratio < TAN_78_75:
            step = 3
        else:
            step = 0
    if step != 0 and ((dx < 0) != (dy < 0)):
        step = ORIENTATIONS - step
    return step


def lattice(size: int, cols: int, radius: int, hub: int) -> dict:
    thickness = (radius - hub) // RINGS
    edges = [radius - (k + 1) * thickness for k in range(RINGS)]
    edges_sq = [edge * edge for edge in edges]
    dots = []
    counts = [0] * RINGS
    shapes = [0] * (RINGS * ORIENTATIONS)
    for row in range(cols):
        dy = (2 * row - (cols - 1)) * (PITCH // 2)
        for col in range(cols):
            dx = (2 * col - (cols - 1)) * (PITCH // 2)
            d = dx * dx + dy * dy
            if d > radius * radius or d < hub * hub:
                continue
            ring = 0
            while ring < RINGS - 1 and d < edges_sq[ring]:
                ring += 1
            turn = (math.atan2(dx, -dy) / (2 * math.pi)) % 1.0
            orientation = orientation_for(dx, dy)
            dots.append([dx, dy, ring, orientation, round(turn, 5)])
            counts[ring] += 1
            shapes[ring * ORIENTATIONS + orientation] += 1
    return {
        "screen": size,
        "cols": cols,
        "radius": radius,
        "hub": hub,
        "pitch": PITCH,
        "dot": DOT,
        "rings": RINGS,
        "ringEdges": edges,
        "ringCounts": counts,
        "orientationCounts": shapes,
        "arms": ARMS,
        "dotFields": ["dx", "dy", "ring", "orientation", "turn"],
        "dots": dots,
    }


def lattices() -> dict[int, dict]:
    """One per screen size; devices that share a size share a lattice."""
    out: dict[int, dict] = {}
    for device, (size, cols, radius, hub, *_rest) in mockup.LATTICES.items():
        if size not in out:
            out[size] = lattice(size, cols, radius, hub)
    return out


def devices() -> list[dict]:
    rows = []
    # `drawnHands` is the configurator's name for a watch the face tells the time
    # on itself — once with drawn hands, now with the time ring. That is a watch
    # with no hands of its own.
    for device, (size, *_rest, hands) in mockup.LATTICES.items():
        rows.append({"id": device, "screen": size, "drawnHands": not hands,
                     "displayMm": round(DISPLAY_INCHES[device] * 25.4, 2)})
    return rows


def monkeyc_block(by_size: dict[int, dict]) -> str:
    flat = []
    for size in sorted(by_size):
        data = by_size[size]
        flat.append(f"        {size}, "
                    + ", ".join(str(n) for n in data["ringCounts"] + data["orientationCounts"]))
    return "\n".join([
        BLOCK_START,
        "    //! Per lattice: the screen, dots per ring outermost first, then dots per",
        "    //! (ring, ARMS row), ring-major.",
        "    const RING_DOTS = [",
        ",\n".join(flat),
        "    ] as Array<Number>;",
        BLOCK_END,
    ])


def render(by_size: dict[int, dict]) -> dict[Path, str]:
    files = {
        OUT_DIR / f"{size}.json": json.dumps(data, separators=(",", ":")) + "\n"
        for size, data in by_size.items()
    }
    files[OUT_DIR / "devices.json"] = json.dumps(devices(), indent=2) + "\n"
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any output is stale")
    args = parser.parse_args(argv)

    by_size = lattices()
    stale = []
    for path, text in render(by_size).items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)

    source = MONKEYC_TEST.read_text()
    start, end = source.index(BLOCK_START), source.index(BLOCK_END) + len(BLOCK_END)
    block = monkeyc_block(by_size)
    if source[start:end] != block:
        stale.append(MONKEYC_TEST)
        if not args.check:
            MONKEYC_TEST.write_text(source[:start] + block + source[end:])

    if args.check and stale:
        print("stale: " + ", ".join(str(p.relative_to(REPO)) for p in stale)
              + " - run python3 tools/geometry_export.py", file=sys.stderr)
        return 1
    for size, data in sorted(by_size.items()):
        print(f"{size}: {len(data['dots'])} dots, rings {data['ringCounts']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
